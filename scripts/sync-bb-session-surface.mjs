import { createHash } from 'node:crypto'
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'packages', 'bb-session-surface', 'dist')
const target = path.join(root, 'public', 'bb-session-surface')
const revisionTarget = path.join(
  root,
  'src',
  'features',
  'agent',
  'components',
  'bb-session-timeline',
  'bb-session-surface-revision.ts',
)
const normalizedRoot = `${path.resolve(root)}${path.sep}`
const normalizedTarget = path.resolve(target)

if (!`${normalizedTarget}${path.sep}`.startsWith(normalizedRoot)) {
  throw new Error(`Refusing to replace unexpected surface target: ${normalizedTarget}`)
}

await rm(normalizedTarget, { recursive: true, force: true })
await mkdir(normalizedTarget, { recursive: true })
await cp(source, normalizedTarget, { recursive: true })

const revisionHash = createHash('sha256')
for (const assetName of ['index.js', 'style.css']) {
  revisionHash.update(assetName)
  revisionHash.update('\0')
  revisionHash.update(await readFile(path.join(source, assetName)))
  revisionHash.update('\0')
}
const revision = revisionHash.digest('hex').slice(0, 16)
const revisionSource = [
  '// Generated by scripts/sync-bb-session-surface.mjs. Do not edit manually.',
  `export const BB_SESSION_SURFACE_REVISION = '${revision}'`,
  '',
].join('\n')

let currentRevisionSource = null
try {
  currentRevisionSource = await readFile(revisionTarget, 'utf8')
} catch (error) {
  if (error?.code !== 'ENOENT') throw error
}
const normalizedCurrentRevisionSource = currentRevisionSource?.replace(/\r\n?/g, '\n') ?? null
if (normalizedCurrentRevisionSource !== revisionSource) {
  await writeFile(revisionTarget, revisionSource, 'utf8')
}

console.log(
  `Synced bb session surface ${revision} to ${path.relative(root, normalizedTarget)}.`,
)
